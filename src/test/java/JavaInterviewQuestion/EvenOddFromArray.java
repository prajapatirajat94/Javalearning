package JavaInterviewQuestion;

import java.awt.desktop.SystemEventListener;

public class EvenOddFromArray {


    public static void main(String[]args) {

        int[]num ={1,2,3,4,5,6};
        for(int i:num){
            if(i%2==0){
                System.out.println(i+" is Even num");
            }else {
                System.out.println(i+" is Odd num");
            }
        }



    }








}
